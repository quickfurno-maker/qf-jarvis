/**
 * The CLOSED synthetic prompt registry (AS4-PREP-A).
 *
 * ### This is the only place benchmark text exists, and it is the layer that must not be realistic
 *
 * RMB-A and RMB-B are content-opaque: a prompt reaches them as a digest and a token count, and there
 * is no field a sentence fits in. Somebody, somewhere, still has to produce the bytes -- and this is
 * that somebody.
 *
 * The pull at this exact point is toward realism. Performance under REAL prompts is what an owner
 * actually wants to know, and the most realistic Riya prompts available are the Human Gold corpus and
 * the protected P10 exam. A benchmark that read either would be a second, ungoverned copy of both,
 * living outside every firewall built for them and committed to a repository as "just fixtures". So
 * the registry is closed, it is generated, and it can reach nothing: no dataset import, no filesystem
 * read, no prompt registry, no customer message, no CRM record, no production system prompt.
 *
 * The cost is stated plainly: these profiles measure how the engine handles a prompt of a given SHAPE
 * and SIZE, not how it handles a real sales conversation. That is the right thing for an operational
 * benchmark to measure -- latency is a function of token counts and structure, not of meaning -- and
 * conversational QUALITY is P10's authority, on evidence this package never produces.
 *
 * ### Deterministic, so a digest authored last week still matches
 *
 * Text is generated by walking a fixed neutral lexicon with a fixed step, so a profile produces the
 * same bytes on every machine and in every process. The digest binds the registry ref, the profile id,
 * the profile version and the materialized messages, which means a change to a single filler word
 * changes the digest and the suite plan refuses to run -- rather than comparing two runs of two
 * different prompts under one case id.
 *
 * ### The words are deliberately meaningless
 *
 * Neutral placeholder tokens, chosen so nothing here can be quoted as a product claim, a price, a
 * policy, a customer detail or a Riya utterance. No brand, no person, no number, no promise.
 */
import { sha256OfCanonical } from '../internal/digest.js';
import { RiyaLocalBenchmarkError } from '../contracts/errors.js';
import type { RiyaLocalChatMessage } from '../contracts/engine-ports.js';

/** Which registry a digest belongs to. Bumped, never edited, if the generation rule changes. */
export const RIYA_SYNTHETIC_PROMPT_REGISTRY_REF = 'riya.local.benchmark.synthetic.v1';
export const RIYA_SYNTHETIC_PROMPT_REGISTRY_VERSION = 1;

export const RIYA_SYNTHETIC_PROMPT_PROFILE_IDS = [
  'synthetic.short.chat.v1',
  'synthetic.medium.chat.v1',
  'synthetic.long.chat.v1',
] as const;
export type RiyaSyntheticPromptProfileId = (typeof RIYA_SYNTHETIC_PROMPT_PROFILE_IDS)[number];

/**
 * The lexicon. Neutral placeholder words with no business, personal or factual content.
 *
 * Greek letters and shape words: they make a sentence that tokenizes like a sentence without asserting
 * anything about anything.
 */
const LEXICON = [
  'alpha',
  'beta',
  'gamma',
  'delta',
  'epsilon',
  'zeta',
  'eta',
  'theta',
  'iota',
  'kappa',
  'lambda',
  'omicron',
  'sigma',
  'tau',
  'upsilon',
  'phi',
  'chi',
  'psi',
  'omega',
  'nu',
] as const;

interface ProfileShape {
  /** How many user/assistant exchanges precede the final user turn. */
  readonly priorExchanges: number;
  /** Words per generated line. */
  readonly wordsPerLine: number;
}

const SHAPES: Readonly<Record<RiyaSyntheticPromptProfileId, ProfileShape>> = Object.freeze({
  'synthetic.short.chat.v1': { priorExchanges: 0, wordsPerLine: 12 },
  'synthetic.medium.chat.v1': { priorExchanges: 4, wordsPerLine: 24 },
  'synthetic.long.chat.v1': { priorExchanges: 12, wordsPerLine: 48 },
});

/**
 * A fixed system line. It describes the SHAPE of the exercise and instructs nothing about a business.
 *
 * A real system prompt would be a production artifact leaking into a benchmark; a benchmark with no
 * system message at all would measure a prompt shape no deployment uses. This is the honest middle:
 * present, structurally representative, and empty of meaning.
 */
const SYSTEM_LINE =
  'You are a synthetic benchmark responder. Reply with ordinary prose of the requested length.';

/**
 * Deterministic filler, from a seeded linear congruential generator.
 *
 * A simple arithmetic stride was tried first and rejected: its period is the lexicon length, so a long
 * profile eventually emits a line it has already emitted. A repeated turn lets an engine's prefix cache
 * answer a later request for free, which turns a latency measurement into a cache-hit measurement --
 * and the number reads as a very fast model rather than as a broken prompt.
 *
 * The constants are the textbook Numerical Recipes ones. They are here for reproducibility, not for
 * statistical quality: nothing about this is random, and every value stays inside the safe-integer
 * range.
 */
function line(seed: number, wordCount: number): string {
  let state = (seed * 2_654_435_761) >>> 0;
  const words: string[] = [];
  for (let index = 0; index < wordCount; index += 1) {
    state = (state * 1_664_525 + 1_013_904_223) >>> 0;
    words.push(LEXICON[state % LEXICON.length] ?? 'alpha');
  }
  return `${words.join(' ')}.`;
}

/** True iff `value` names a profile in this closed registry. */
export function isRiyaSyntheticPromptProfileId(
  value: string,
): value is RiyaSyntheticPromptProfileId {
  return (RIYA_SYNTHETIC_PROMPT_PROFILE_IDS as readonly string[]).includes(value);
}

/**
 * The exact messages for one profile. Throws `PROMPT_PROFILE_UNKNOWN` for anything else.
 *
 * There is no parameter for "supply your own text", and that is the point: a caller cannot widen this
 * registry without editing this file, and editing this file changes every digest it produces, which
 * makes every suite plan authored against the old bytes refuse to run.
 */
export function materializeRiyaSyntheticPromptProfile(
  profileId: string,
): readonly RiyaLocalChatMessage[] {
  if (!isRiyaSyntheticPromptProfileId(profileId)) {
    throw new RiyaLocalBenchmarkError('PROMPT_PROFILE_UNKNOWN');
  }
  const shape = SHAPES[profileId];
  const messages: RiyaLocalChatMessage[] = [{ role: 'system', content: SYSTEM_LINE }];
  for (let exchange = 0; exchange < shape.priorExchanges; exchange += 1) {
    messages.push({ role: 'user', content: line(exchange * 2 + 1, shape.wordsPerLine) });
    messages.push({ role: 'assistant', content: line(exchange * 2 + 2, shape.wordsPerLine) });
  }
  messages.push({
    role: 'user',
    content: line(shape.priorExchanges * 2 + 1, shape.wordsPerLine),
  });
  return Object.freeze(messages.map((message) => Object.freeze(message)));
}

/**
 * The digest a suite plan must declare for a profile.
 *
 * Bound to the registry ref and version as well as the bytes, so two registries that happened to
 * generate identical text would still be distinguishable -- an identity that says only "these bytes"
 * cannot tell you which rule produced them.
 */
export function riyaSyntheticPromptProfileDigest(profileId: string): string {
  const messages = materializeRiyaSyntheticPromptProfile(profileId);
  return sha256OfCanonical({
    registryRef: RIYA_SYNTHETIC_PROMPT_REGISTRY_REF,
    registryVersion: RIYA_SYNTHETIC_PROMPT_REGISTRY_VERSION,
    profileId,
    messages,
  });
}
